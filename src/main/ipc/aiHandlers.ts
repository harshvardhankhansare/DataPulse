import { ipcMain } from 'electron';
import { detectSchema } from '../../core/schema/typeDetector.js';
import { LocalAiClient } from '../../core/ai/localAiClient.js';
import { buildSystemPrompt, buildUserPrompt } from '../../core/ai/promptBuilder.js';
import { validateSql } from '../../core/ai/sqlValidator.js';
import { mapAiResultToChart } from '../../core/ai/aiResultMapper.js';
import { heuristicQuery } from '../../core/ai/heuristicQuery.js';

export function registerAiHandlers(query: (sql: string) => Promise<any[]>) {
  const aiClient = new LocalAiClient();

  ipcMain.handle('check-ai-status', async (_event, customUrl?: string) => {
    return await aiClient.checkStatus(customUrl);
  });

  ipcMain.handle('query-ai', async (_event, tableName: string, question: string, customUrl?: string) => {
    try {
      const schema = await detectSchema(tableName, query);

      // First, try to get AI response
      let aiResult = null;
      let aiError = null;

      try {
        const systemPrompt = buildSystemPrompt(tableName, schema);
        const userPrompt = buildUserPrompt(question);

        const rawSql = await aiClient.generateSql(userPrompt, systemPrompt, customUrl);
        const validation = validateSql(rawSql, tableName);

        if (validation.valid && validation.cleanSql) {
          aiResult = {
            success: true,
            sql: validation.cleanSql,
            validation,
          };
        } else {
          aiError = validation.error || 'SQL generated by AI failed validation.';
        }
      } catch (err) {
        // AI call failed, we'll try heuristic below
        aiError = err instanceof Error ? err.message : String(err);
      }

      // If AI succeeded, use it
      if (aiResult) {
        const rows = await query(aiResult.sql);
        const chartConfig = mapAiResultToChart(question, rows);

        return {
          success: true,
          sql: aiResult.sql,
          rows,
          chartConfig,
          heuristic: false,
          heuristicExplanation: undefined,
        };
      }

      // AI failed or unavailable, try heuristic query as fallback
      const heuristicResult = heuristicQuery(question, schema);
      if (heuristicResult) {
        // Validate the heuristic SQL
        const validation = validateSql(heuristicResult.sql, tableName);
        if (validation.valid && validation.cleanSql) {
          const rows = await query(validation.cleanSql);
          const chartConfig = mapAiResultToChart(question, rows);

          return {
            success: true,
            sql: validation.cleanSql,
            rows,
            chartConfig,
            // We'll add a flag to indicate this was heuristic for the UI
            heuristic: true,
            heuristicExplanation: heuristicResult.explanation,
          };
        } else {
          // Heuristic SQL failed validation
          return {
            success: false,
            error: validation.error || 'Generated heuristic SQL failed validation.',
            sql: heuristicResult.sql,
          };
        }
      }

      // Both AI and heuristic failed
      return {
        success: false,
        error: aiError || 'Unable to generate query from question. AI service unavailable and no matching heuristic rule found.',
      };
    } catch (error) {
      console.error('AI query error:', error);
      return {
        success: false,
        error: error instanceof Error ? error.message : String(error),
      };
    }
  });
}
